using System.IO;
using System.Diagnostics;
using System.Text.RegularExpressions;

namespace RepoLegibility.Core;

/// <summary>Reads a repo zip and reports what its code does and how legible that is. Runs nothing from the zip.</summary>
public static class Analyzer
{
    private static readonly Regex GeneratedName = new(@"(?i)\.(?:g|g\.i|designer|generated|AssemblyInfo|AssemblyAttributes)\.cs$", RegexOptions.Compiled);
    private static readonly Regex GeneratedHeader = new(@"<auto-generated", RegexOptions.Compiled);

    private static readonly HashSet<string> OtherLanguages = new(StringComparer.OrdinalIgnoreCase)
    {
        ".ps1", ".psm1", ".psd1", ".cmd", ".bat", ".sh", ".js", ".mjs", ".ts", ".py", ".vb", ".fs", ".fsx", ".cpp", ".c", ".h",
        ".hpp", ".go", ".rs", ".java", ".kt", ".rb", ".php", ".vbs", ".wsf", ".razor", ".cshtml", ".csx", ".sql", ".lua"
    };

    /// <summary>
    /// Every pattern runs on code from a stranger's zip: a match that takes longer than this stops,
    /// so crafted source can't stall a scan. Set once, before the first pattern is built.
    /// </summary>
    public static void LimitPatternTime() =>
        AppContext.SetData("REGEX_DEFAULT_MATCH_TIMEOUT", TimeSpan.FromSeconds(2));

    /// <param name="report">Progress: a detail line, and done and total where they are real.</param>
    public static ScanReport Analyze(string zipPath, string toolVersion, Action<string, int?, int?>? report = null)
    {
        var clock = Stopwatch.StartNew();
        report?.Invoke("Opening " + Path.GetFileName(zipPath), null, null);
        var archive = RepoArchive.Read(zipPath, report);

        report?.Invoke("Reading the projects", null, null);
        var projects = ProjectScan.Read(archive.Files);

        Origin OriginOf(string path)
        {
            if (path.StartsWith(".github/", StringComparison.OrdinalIgnoreCase)) return Origin.CI;
            var ext = Path.GetExtension(path).ToLowerInvariant();
            if (ext is ".csproj" or ".props" or ".targets") return Origin.Build;
            var owner = ProjectScan.Owner(projects, path);
            return owner is { IsTest: true } ? Origin.Tests : Origin.App;
        }
        string? ProjectOf(string path) => ProjectScan.Owner(projects, path)?.Name;

        // The C# the scan reads: every .cs file except those a project leaves out of its build.
        var codeFiles = new List<CodeFile>();
        var removed = new List<string>();
        foreach (var file in archive.Files.Where(f => f.Extension == ".cs" && f.Text is not null))
        {
            var owner = ProjectScan.Owner(projects, file.Path);
            if (owner is not null && ProjectScan.IsRemoved(owner, file.Path)) { removed.Add(file.Path); continue; }
            bool generated = GeneratedName.IsMatch(file.Path) || GeneratedHeader.IsMatch(file.Text!.Length > 2000 ? file.Text[..2000] : file.Text);
            codeFiles.Add(new CodeFile(file, OriginOf(file.Path), owner, generated));
        }
        var code = new CodeBase(codeFiles, archive.Files);

        var findings = new List<Finding>();
        report?.Invoke("Looking for elevation", null, null);
        findings.AddRange(TextScan.Manifests(archive.Files, projects, OriginOf));
        bool elevated = findings.Any(f => f.Kind == FindingKind.Elevation && f.Origin == Origin.App);

        report?.Invoke("Following the code", 0, codeFiles.Count);
        var skipped = new List<string>();
        findings.AddRange(CodeScan.Scan(code, elevated, report, skipped));

        report?.Invoke("Native calls, embedded data and secrets", null, null);
        findings.AddRange(TextScan.PInvokes(codeFiles, elevated, out int pinvokes));
        findings.AddRange(TextScan.Privileges(codeFiles));
        findings.AddRange(TextScan.EmbeddedData(codeFiles));
        findings.AddRange(TextScan.Secrets(archive.Files, OriginOf, ProjectOf));

        report?.Invoke("Build files and CI", null, null);
        findings.AddRange(TextScan.BuildFiles(archive.Files, ProjectOf));
        findings.AddRange(TextScan.Scripts(archive.Files, OriginOf));
        var ciActions = new List<CiAction>();
        findings.AddRange(TextScan.Workflows(archive.Files, ciActions));

        // Written so it can't be read (encoded, char codes, fragments): obscured, apart from what can't be
        // shown by nature. The author made that choice; these are read first.
        foreach (var f in findings.Where(f => f.HiddenOnPurpose && f.Legibility is Legibility.Opaque or Legibility.Untraced or Legibility.PartlyClear or Legibility.Clear))
            f.Legibility = Legibility.Obscured;

        // One finding per place and kind; then the order the report reads in.
        findings = findings
            .GroupBy(f => (f.File, f.Line, f.Kind, f.Target))
            .Select(g => g.OrderByDescending(f => f.Legibility).First())
            .GroupBy(f => (f.File, f.Line, f.Kind))
            .SelectMany(g => g.Key.Kind == FindingKind.Secret ? g.Take(1) : g)
            .OrderBy(f => f.Origin == Origin.Tests)
            .ThenBy(f => f.Scope)
            .ThenByDescending(f => f.Legibility)
            .ThenBy(f => f.File, StringComparer.OrdinalIgnoreCase)
            .ThenBy(f => f.Line)
            .ToList();

        report?.Invoke("Cutting excerpts", null, null);
        var byPath = codeFiles.ToDictionary(f => f.Path, StringComparer.OrdinalIgnoreCase);
        var texts = archive.Files.Where(f => f.Text is not null).ToDictionary(f => f.Path, f => f.Text!, StringComparer.OrdinalIgnoreCase);
        for (int i = 0; i < findings.Count; i++)
        {
            findings[i].Id = i + 1;
            findings[i].NotCalledByApp = NotCalledByApp(findings[i]);
            // Every way to it is code only tests call: that's what the target says, not "not traced".
            if (findings[i].NotCalledByApp && findings[i].Target == Finding.NotTraced) findings[i].Target = Finding.OnlyTestsReach;
            findings[i].Direction = DirectionOf(findings[i]);
            findings[i].Excerpt = byPath.TryGetValue(findings[i].File, out var cf)
                ? Excerpts.ForCode(cf, findings[i].Line, findings[i].Legibility is Legibility.Obscured or Legibility.Opaque or Legibility.Untraced)
                : texts.TryGetValue(findings[i].File, out var text) ? Excerpts.ForText(text, findings[i].Line) : null;
        }
        AssignKeys(findings);
        var settingsFile = WhoDecides.SettingsFileOf(findings);
        foreach (var f in findings) f.WhoDecides = WhoDecides.Of(f, settingsFile);
        foreach (var f in findings.Where(f => f.NotCalledByApp))
            if (WhatTestsPass(f, code) is { } passed)
                f.Notes = [.. f.Notes, passed];

        report?.Invoke("Counting", null, null);
        var metrics = Measure(archive, codeFiles, pinvokes, TextScan.UnsafeBlocks(codeFiles));

        var projectInfos = projects.Select(p => new ProjectInfo(p.Path, p.Name, p.Kind, p.Frameworks, p.Ui, p.IsTest,
            codeFiles.Where(c => c.Project == p && !c.Generated).Sum(Sloc))).ToList();

        var packages = projects
            .SelectMany(p => p.Packages.Select(pk => new PackageInfo(pk.Name, pk.Version, p.Name, p.IsTest)))
            .OrderBy(p => p.TestOnly).ThenBy(p => p.Name, StringComparer.OrdinalIgnoreCase)
            .ToList();

        var references = projects.SelectMany(p =>
                p.ProjectReferences.Select(r => new ReferenceInfo("Project", Path.GetFileNameWithoutExtension(r.Replace('\\', '/')), p.Name))
                .Concat(p.FrameworkReferences.Select(r => new ReferenceInfo("Framework", r, p.Name)))
                .Concat(p.DllReferences.Select(r => new ReferenceInfo("DLL file", r, p.Name))))
            .ToList();

        var notCovered = new List<string>();
        foreach (var group in archive.Files.Where(f => OtherLanguages.Contains(f.Extension)).GroupBy(f => f.Extension.ToLowerInvariant()).OrderBy(g => g.Key))
            notCovered.Add($"{group.Count()} {group.Key} file{(group.Count() == 1 ? "" : "s")} (not C#; not scanned): " +
                           string.Join(", ", group.Take(4).Select(f => f.Path)) + (group.Count() > 4 ? ", …" : ""));
        foreach (var f in archive.Files.Where(f => f.SkippedTooLarge))
            notCovered.Add($"{f.Path} ({f.Bytes / 1024 / 1024} MB): too large to read.");
        notCovered.AddRange(skipped);
        foreach (var r in removed)
            notCovered.Add($"{r}: left out of its project's build (Compile Remove), so not scanned.");
        if (findings.Any(f => f.Kind == FindingKind.BuildStep && f.Call.StartsWith("<UsingTask")))
            notCovered.Add("Inline build tasks: the C# inside build files is listed, not followed.");
        if (packages.Count > 0)
            notCovered.Add("NuGet packages: their code isn't in the zip. A package can also run its own build steps and analyzers.");
        if (references.Any(r => r.Kind == "DLL file"))
            notCovered.Add("Referenced DLL files: compiled code, not readable here.");

        var combinations = Combined.Find(findings, archive.Files);
        clock.Stop();
        var scan = new ScanReport
        {
            ZipName = archive.ZipName,
            ZipSha256 = archive.Sha256,
            ZipBytes = archive.ZipBytes,
            RepoName = archive.RepoName,
            ScannedAt = DateTime.Now,
            Took = clock.Elapsed,
            ToolVersion = toolVersion,
            Findings = findings,
            Metrics = metrics,
            Projects = projectInfos,
            Packages = packages,
            References = references,
            CiActions = ciActions,
            BlackBoxes = archive.Files.Where(f => f.BlackBoxKind is not null)
                .Select(f => new BlackBox(f.Path, f.Bytes, f.BlackBoxKind!, f.Sha256 ?? "")).ToList(),
            Endpoints = Endpoints(TextScan.Endpoints(archive.Files.Where(f => OriginOf(f.Path) != Origin.Tests).ToList(),
                codeFiles.Where(c => c.Origin != Origin.Tests).ToList()), findings, codeFiles),
            NotCovered = notCovered,
            Combinations = combinations
        };
        scan.Overview = Overview.Build(scan, combinations, label => Combined.Declares(archive.Files, label), Combined.HasReadme(archive.Files), Combined.SecurityWriting(archive.Files));
        return scan;
    }

    /// <summary>Lines of code: non-blank once comments are blanked.</summary>
    public static int Sloc(CodeFile file) =>
        file.Text.Split('\n').Count(l => !string.IsNullOrWhiteSpace(l));

    private static Metrics Measure(RepoArchive archive, List<CodeFile> code, int pinvokes, int unsafeBlocks)
    {
        int sloc = 0, comments = 0, generatedSloc = 0, generatedFiles = 0, testSloc = 0;
        var sizes = new List<FileSize>();
        foreach (var file in code)
        {
            var original = file.Original.Split('\n');
            var text = file.Text.Split('\n');
            int fileSloc = 0;
            for (int i = 0; i < text.Length; i++)
            {
                if (!string.IsNullOrWhiteSpace(text[i])) fileSloc++;
                else if (i < original.Length && !string.IsNullOrWhiteSpace(original[i])) comments++;
            }
            if (file.Generated) { generatedFiles++; generatedSloc += fileSloc; continue; }
            if (file.Origin == Origin.Tests) testSloc += fileSloc;
            sloc += fileSloc;
            sizes.Add(new FileSize(file.Path, fileSloc));
        }

        int xaml = archive.Files.Where(f => f.Extension == ".xaml" && f.Text is not null)
            .Sum(f => f.Text!.Split('\n').Count(l => !string.IsNullOrWhiteSpace(l)));

        return new Metrics
        {
            Files = archive.Files.Count,
            Bytes = archive.Files.Sum(f => f.Bytes),
            CsFiles = code.Count,
            Sloc = sloc,
            CommentLines = comments,
            GeneratedFiles = generatedFiles,
            GeneratedSloc = generatedSloc,
            XamlLines = xaml,
            TestSloc = testSloc,
            ByExtension = archive.Files
                .GroupBy(f => f.Extension.Length == 0 ? "(none)" : f.Extension.ToLowerInvariant())
                .Select(g => (g.Key, g.Count()))
                .OrderByDescending(x => x.Item2).ThenBy(x => x.Key)
                .ToList(),
            Largest = sizes.OrderByDescending(s => s.Sloc).Take(5).ToList(),
            PInvokes = pinvokes,
            UnsafeBlocks = unsafeBlocks,
            // The switch that lets C# use pointers: worth knowing even when no unsafe code is there yet.
            UnsafeAllowedIn = archive.Files
                .Where(f => f.Extension.Equals(".csproj", StringComparison.OrdinalIgnoreCase) && f.Text is not null
                            && Regex.IsMatch(f.Text, @"<AllowUnsafeBlocks>\s*true\s*</AllowUnsafeBlocks>", RegexOptions.IgnoreCase))
                .Select(f => f.Path).OrderBy(p => p, StringComparer.OrdinalIgnoreCase).ToList()
        };
    }

    /// <summary>
    /// The web addresses named in the repo, plus the ones the code hides and the scan worked out
    /// (marked decoded or assembled). An HttpClient BaseAddress that no relative request uses is marked:
    /// naming it isn't talking to it.
    /// </summary>
    private static List<Endpoint> Endpoints(List<Endpoint> named, List<Finding> findings, IReadOnlyList<CodeFile> code)
    {
        var shipped = findings.Where(f => f.Origin != Origin.Tests).ToList();
        var list = new List<Endpoint>(named);
        foreach (var f in shipped.Where(f => f.HiddenOnPurpose))
        {
            var m = Regex.Match(f.Target, @"^(?<u>(?:https?|wss?|ftp)://[^\s()]+)\s*\((?<how>decoded|assembled)\)");
            if (!m.Success) continue;
            var url = m.Groups["u"].Value.TrimEnd('/');
            var host = Regex.Match(url, @"^[a-z]+://(?<h>[^/:?#]+)", RegexOptions.IgnoreCase).Groups["h"].Value;
            if (list.Any(e => e.Url.Equals(url, StringComparison.OrdinalIgnoreCase))) continue;
            list.Add(new Endpoint(url, host, [$"{f.File}:{f.Line}"], m.Groups["how"].Value + ", hidden in the code"));
        }

        // An address the code requests or opens is listed even where the text list leaves its host out as
        // documentation (example.org, aka.ms): that it's used is what counts.
        foreach (var f in shipped.Where(f => f.Kind == FindingKind.Network && !f.HiddenOnPurpose))
        {
            var m = Regex.Match(f.Target, @"^(?<u>(?:https?|wss?|ftp)://[^\s()]+)");
            if (!m.Success) continue;
            var url = m.Groups["u"].Value.TrimEnd('/', '.', ',', ';');
            var host = Regex.Match(url, @"^[a-z]+://(?<h>[^/:?#]+)", RegexOptions.IgnoreCase).Groups["h"].Value;
            if (host.Length == 0 || host.Contains('{') || list.Any(e => e.Url.Equals(url, StringComparison.OrdinalIgnoreCase))) continue;
            list.Add(new Endpoint(url, host, [$"{f.File}:{f.Line}"], f.Summary.Contains("in the browser", StringComparison.Ordinal) ? "opened in the browser" : null));
        }

        bool relativeUsed = shipped.Any(f => f.Notes.Any(n => n.Contains("joined to the client's BaseAddress", StringComparison.Ordinal)));
        var bases = code.Where(c => c.Origin != Origin.Tests)
            .SelectMany(c => Regex.Matches(c.Text, @"BaseAddress\s*=\s*new\s+Uri\s*\(\s*@?""(?<u>[^""]+)""").Select(m => m.Groups["u"].Value.TrimEnd('/')))
            .ToHashSet(StringComparer.OrdinalIgnoreCase);
        for (int i = 0; i < list.Count; i++)
            if (!relativeUsed && list[i].Note is null && bases.Contains(list[i].Url))
                list[i] = list[i] with { Note = "a client's BaseAddress; no relative request uses it, so it's likely never contacted" };

        return list.OrderBy(e => e.Host, StringComparer.OrdinalIgnoreCase).ThenBy(e => e.Url, StringComparer.OrdinalIgnoreCase).ToList();
    }

    /// <summary>
    /// A key that stays with a finding across scans and code changes: from its kind, file, member, call
    /// and which occurrence of that call in the member it is. The line number stays out, so edits
    /// elsewhere in the file don't move it; renaming the file, the member or the call does. Shown
    /// beside the running #n: "N-3f2a1c" (N for network; F files, R registry, P processes, C code,
    /// A accounts and secrets, B build and CI, E elevation, O other).
    /// </summary>
    private static void AssignKeys(List<Finding> findings)
    {
        var used = new HashSet<string>(StringComparer.Ordinal);
        foreach (var group in findings
                     .GroupBy(f => (f.Kind, f.File, Member: MemberName(f), f.Call))
                     .OrderBy(g => g.Key.File, StringComparer.Ordinal).ThenBy(g => g.Key.Member, StringComparer.Ordinal)
                     .ThenBy(g => g.Key.Call, StringComparer.Ordinal).ThenBy(g => g.Key.Kind))
        {
            int n = 0;
            foreach (var f in group.OrderBy(f => f.Line))
            {
                var basis = $"{f.Kind}|{f.File.Replace('\\', '/').ToLowerInvariant()}|{group.Key.Member}|{f.Call}|{n++}";
                var hash = Convert.ToHexStringLower(System.Security.Cryptography.SHA256.HashData(System.Text.Encoding.UTF8.GetBytes(basis)))[..6];
                var key = KindLetter(f.Kind) + "-" + hash;
                for (int k = 2; !used.Add(key); k++) key = KindLetter(f.Kind) + "-" + hash + "-" + k;
                f.Key = key;
            }
        }
    }

    private static string MemberName(Finding f) =>
        f.Excerpt?.Member is { } m ? Regex.Match(m, @"^[^(]*").Value.Trim() : "";

    private static char KindLetter(FindingKind kind) => kind switch
    {
        FindingKind.FileWrite or FindingKind.FileDelete or FindingKind.FileRead or FindingKind.FolderListing => 'F',
        FindingKind.RegistryWrite or FindingKind.RegistryRead => 'R',
        FindingKind.Network or FindingKind.Listens => 'N',
        FindingKind.Process or FindingKind.Service or FindingKind.Wmi => 'P',
        FindingKind.Reflection or FindingKind.LoadsCode or FindingKind.NativeCode or FindingKind.Com => 'C',
        FindingKind.Identity or FindingKind.Credential or FindingKind.Secret => 'A',
        FindingKind.BuildStep or FindingKind.CiStep or FindingKind.CiAction => 'B',
        FindingKind.Elevation => 'E',
        FindingKind.Combination => 'T',
        _ => 'O'
    };

    /// <summary>
    /// For code only tests reach: what the test passes in, traced at the test's call. Marked as the
    /// test's value, since the app itself never calls it: "Tests call SortDictionary with: temp folder › words.dic".
    /// </summary>
    private static string? WhatTestsPass(Finding f, CodeBase code)
    {
        var reason = f.Reasons.Concat(f.Calls.Select(c => c.Reason ?? "")).FirstOrDefault(r => r.Contains(CodeBase.OnlyTests, StringComparison.Ordinal));
        if (reason is null) return null;
        var m = Regex.Match(reason, @"parameter (?<p>\w+) of (?<m>\w+),.*\((?<file>[^():]+):(?<line>\d+)\)");
        if (!m.Success) return null;
        string parameter = m.Groups["p"].Value, method = m.Groups["m"].Value;
        var testFile = code.Files.FirstOrDefault(c => c.Path == m.Groups["file"].Value);
        if (testFile is null) return null;

        // Which parameter it is, from the method's declaration.
        int index = -1;
        foreach (var file in code.Files.Where(c => c.Origin != Origin.Tests))
        {
            var decl = Regex.Match(file.Masked, @"\b" + Regex.Escape(method) + @"\s*(?:<[^<>]*>)?\s*\((?<ps>[^()]*)\)\s*(?:=>|\{|where\b)");
            if (!decl.Success) continue;
            var names = decl.Groups["ps"].Value.Split(',').Select(p => Regex.Match(p, @"(\w+)\s*(?:=[^,]*)?$").Groups[1].Value).ToList();
            index = names.IndexOf(parameter);
            if (index >= 0) break;
        }
        if (index < 0) return null;

        // The call on that line of the test.
        int lineStart = 0;
        for (int l = 1; l < int.Parse(m.Groups["line"].Value) && lineStart >= 0; l++) lineStart = testFile.Masked.IndexOf('\n', lineStart) + 1;
        if (lineStart <= 0 && m.Groups["line"].Value != "1") return null;
        var call = new Regex(@"\b" + Regex.Escape(method) + @"\s*\(").Match(testFile.Masked, lineStart);
        if (!call.Success || testFile.LineOf(call.Index) > testFile.LineOf(lineStart) + 2) return null;
        var args = testFile.Arguments(call.Index + call.Length);
        if (index >= args.Count) return null;
        var t = Tracer.Run(code, Tracer.StripNamed(args[index]), testFile, call.Index);
        var value = t.Describe();
        if (value.StartsWith("not determined", StringComparison.Ordinal)) return null;
        return $"Tests call {method} with: {value} (a test's value; the app itself doesn't call it).";
    }

    /// <summary>Which way a finding moves things, from its kind and, where the kind allows both, from what it says it does.</summary>
    private static Direction DirectionOf(Finding f)
    {
        if (f.Unused) return Direction.None;
        var s = f.Summary;
        bool Starts(params string[] words) => words.Any(w => s.Contains(w, StringComparison.Ordinal));
        return f.Kind switch
        {
            FindingKind.FileRead or FindingKind.RegistryRead or FindingKind.FolderListing or FindingKind.Identity
                or FindingKind.Wmi or FindingKind.Environment => Direction.Reads,
            FindingKind.FileWrite or FindingKind.FileDelete or FindingKind.RegistryWrite or FindingKind.Service => Direction.Changes,
            FindingKind.Clipboard => Starts("Writes", "Sets", "Puts", "Copies") ? Direction.Changes : Direction.Reads,
            FindingKind.EventLog => Starts("Reads") ? Direction.Reads : Direction.Changes,
            FindingKind.Database => Direction.Reads | Direction.Changes,
            FindingKind.Network when Starts("in the browser") => Direction.Runs,
            FindingKind.Network when Starts("Downloads", "Looks up the address") => Direction.Receives,
            FindingKind.Network => Direction.Sends | Direction.Receives,
            FindingKind.Listens => Direction.Receives,
            // A CI secret put in a step's environment is read there; nothing in the source sends it.
            FindingKind.Credential when f.Origin == Origin.CI && f.Call == "secrets." => Direction.Reads,
            FindingKind.Credential => Direction.Sends,
            FindingKind.Process or FindingKind.LoadsCode or FindingKind.NativeCode or FindingKind.Elevation
                or FindingKind.BuildStep or FindingKind.CiStep or FindingKind.CiAction => Direction.Runs,
            FindingKind.Com when Starts("Drives", "Creates") => Direction.Runs,
            FindingKind.Reflection when Starts("Creates") => Direction.Runs,
            _ => Direction.None
        };
    }

    /// <summary>Every way to the finding ends at a method only tests call: one call, or each of the helper's calls.</summary>
    private static bool NotCalledByApp(Finding f)
    {
        if (f.Origin == Origin.Tests || f.CallsNotFollowed > 0) return false;
        static bool Only(string? reason) => reason?.Contains(CodeBase.OnlyTests, StringComparison.Ordinal) == true;
        return f.Calls.Count > 0
            ? f.Calls.All(c => Only(c.Reason))
            : f.Reasons.Count > 0 && f.Reasons.Any(Only) && f.Reasons.All(r => Only(r) || !r.StartsWith("Ends at", StringComparison.Ordinal) && !r.StartsWith("Depends on", StringComparison.Ordinal));
    }
}

/// <summary>Source lines around a finding: a few lines for most, the whole member (capped) for opaque ones.</summary>
public static class Excerpts
{
    private const int Around = 3;
    private const int MaxMember = 60;

    public static Excerpt ForCode(CodeFile file, int line, bool wholeMember)
    {
        var member = MethodLocator.Enclosing(file.Masked, Position(file, line));
        if (wholeMember && MemberSpan(file, line) is (int from, int to) && to - from + 1 <= MaxMember)
            return Cut(file, from, to, line, member);
        if (wholeMember && MemberSpan(file, line) is (int f2, int t2))
        {
            int start = Math.Max(f2, line - MaxMember / 2);
            int end = Math.Min(t2, start + MaxMember - 1);
            return Cut(file, start, end, line, member);
        }
        return Cut(file, Math.Max(1, line - Around), Math.Min(file.LineCount, line + Around), line, member);
    }

    public static Excerpt ForText(string text, int line)
    {
        var lines = text.Split('\n');
        int from = Math.Max(1, line - Around), to = Math.Min(lines.Length, line + Around);
        return new Excerpt(from, line, lines[(from - 1)..to].Select(l => l.TrimEnd('\r')).ToList(), null);
    }

    private static Excerpt Cut(CodeFile file, int from, int to, int focus, string? member) =>
        new(from, focus, Enumerable.Range(from, to - from + 1).Select(file.LineText).ToList(), member);

    private static int Position(CodeFile file, int line)
    {
        int pos = 0, current = 1;
        while (current < line && pos < file.Original.Length)
        {
            int next = file.Original.IndexOf('\n', pos);
            if (next < 0) break;
            pos = next + 1;
            current++;
        }
        // The first non-blank character of the line, so the position is inside the statement.
        while (pos < file.Original.Length && file.Original[pos] is ' ' or '\t') pos++;
        return pos;
    }

    /// <summary>The lines of the innermost member body around a line: the brace that opens it to the one that closes it.</summary>
    private static (int From, int To)? MemberSpan(CodeFile file, int line)
    {
        var masked = file.Masked;
        int position = Position(file, line);
        int depth = 0;
        for (int i = Math.Min(position, masked.Length) - 1; i >= 0; i--)
        {
            char c = masked[i];
            if (c == '}') { depth++; continue; }
            if (c != '{') continue;
            if (depth > 0) { depth--; continue; }

            int headerStart = masked.LastIndexOfAny([';', '{', '}'], Math.Max(0, i - 1)) + 1;
            var header = masked[headerStart..i].TrimEnd();
            if (Regex.IsMatch(header, @"\b(?:class|struct|record|interface|namespace|enum)\b")) return null;
            if (!header.EndsWith(')') && !Regex.IsMatch(header, @"\b(?:get|set|init)$|[A-Za-z_]\w*$")) continue;
            if (Regex.IsMatch(header, @"\b(?:if|for|foreach|while|using|switch|catch|lock|fixed)\s*\(") && header.TrimStart().StartsWith("if") ) continue;
            if (Regex.IsMatch(header.TrimStart(), @"^(?:if|for|foreach|while|using|switch|catch|lock|fixed|else|try|finally|do)\b")) continue;
            int close = file.MatchingBrace(i);
            if (close < 0) return null;
            return (file.LineOf(headerStart + (header.Length - header.TrimStart().Length)), file.LineOf(close));
        }
        return null;
    }

